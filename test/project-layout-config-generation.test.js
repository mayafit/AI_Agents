test('AC3: generation is called from install and reconfigure only — both inside the project-scope gate', () => {
  // FR251 / Story 31.11: a GLOBAL install must perform no project-scoped work,
  // and generating a project's config.yaml is project-scoped. An ungated call
  // site would violate that silently, so the count and the gating are pinned.
  const callSites = CLI_SOURCE.split('\n')
    .map((line, i) => ({ line, n: i + 1 }))
    .filter(({ line }) => /^\s*(await\s+)?generateBmmConfig\s*\(/.test(line));
  assert.strictEqual(callSites.length, 2,
    `generateBmmConfig must be called from exactly two production sites (install + reconfigure), ` +
    `found ${callSites.length}: ${JSON.stringify(callSites)}`);

  // The install call site must sit inside `if (installScope === 'project') {`.
  //
  // Found by BRACE BALANCE, not by `indexOf` on the gate text: `bin/cli.js`
  // contains FOUR `installScope === 'project'` gates, so `indexOf` picks the
  // first one — several hundred lines above the call — and the test then
  // "detects" a gate closing in between and fails for a reason that has nothing
  // to do with the property. (It did exactly that on this suite's first run.)
  // Walking back from the call to its own enclosing `{` answers the actual
  // question: which block is this statement in?
  const lines = CLI_SOURCE.split('\n');
  function enclosingBlockOpenerLine(callLineNumber) {
    let depth = 0;
    for (let i = callLineNumber - 2; i >= 0; i--) {
      const l = lines[i];
      for (let c = l.length - 1; c >= 0; c--) {
        if (l[c] === '}') depth++;
        else if (l[c] === '{') {
          if (depth === 0) return i + 1;
          depth--;
        }
      }
    }
    return -1;
  }

  const gated = callSites
    .map((site) => ({ site, opener: enclosingBlockOpenerLine(site.n) }))
    .filter(({ opener }) => opener > 0 && /installScope === 'project'/.test(lines[opener - 1]));

  assert.strictEqual(gated.length, 1,
    `exactly one call site — the installer's — must be directly inside an ` +
    `\`if (installScope === 'project')\` block. Found ${gated.length}. ` +
    `FR251 forbids a global install performing project-scoped work, and generating a ` +
    `project's config.yaml is project-scoped; an ungated install-time call site would ` +
    `violate that silently and break Story 31.11 AC3. Call sites and their enclosing ` +
    `openers: ${JSON.stringify(callSites.map((s) => ({
      call: s.n, opener: enclosingBlockOpenerLine(s.n),
      openerText: (lines[enclosingBlockOpenerLine(s.n) - 1] || '').trim(),
    })))}`);

  // The other call site is `handleConfigLayout` — the `ma-agents config layout`
  // reconfigure command, which is inherently project-scoped (it is refusing to
  // exist at all without a project) and correctly ungated.
  const ungated = callSites.filter((s) => !gated.some((g) => g.site.n === s.n));
  assert.strictEqual(ungated.length, 1, 'the remaining call site must be the reconfigure one');
});


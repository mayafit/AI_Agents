#!/usr/bin/env node
/**
 * Bug 27.14 — output-folder propagation normalization pass.
 *
 * When bmb (output folder "skills") and gds are co-installed, upstream
 * bmad-method's suffix-match output-folder resolution pins gds artifact paths
 * to `{project-root}/skills/...` instead of the chosen `[core] output_folder`.
 * The ma-agents post-install pass (normalizeModuleOutputFolders) re-reads the
 * canonical output folder from `_bmad/config.toml` and repoints any
 * contaminated module artifact path back at it — in both config.toml and each
 * `_bmad/<mod>/config.yaml`.
 */
'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const os = require('os');

let passed = 0;
let failed = 0;
const errors = [];

function test(name, fn) {
  try {
    fn();
    console.log(`  ✓ ${name}`);
    passed++;
  } catch (err) {
    console.error(`  ✗ ${name}: ${err.message}`);
    failed++;
    errors.push({ name, error: err.message });
  }
}

const { normalizeModuleOutputFolders, correctArtifactPath } = require('../lib/bmad');

function mktemp() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'ma-agents-27-14-'));
}
function cleanup(dir) {
  try { fs.rmSync(dir, { recursive: true, force: true }); } catch {}
}

// Mimics a real Workshop install with bmb+gds co-installed and a CUSTOM output
// folder. gds artifact paths are contaminated with bmb's "skills" segment.
function writeContaminatedProject(dir, outputFolder) {
  const bmad = path.join(dir, '_bmad');
  fs.mkdirSync(path.join(bmad, 'gds'), { recursive: true });
  fs.mkdirSync(path.join(bmad, 'bmm'), { recursive: true });
  fs.mkdirSync(path.join(bmad, 'bmb'), { recursive: true });

  const toml = [
    '# Installer-managed. Regenerated on every install — treat as read-only.',
    '',
    '[core]',
    'project_name = "Workshop"',
    `output_folder = "${outputFolder}"`,
    '',
    '[modules.bmm]',
    `planning_artifacts = "{project-root}/${outputFolder}/planning-artifacts"`,
    `implementation_artifacts = "{project-root}/${outputFolder}/implementation-artifacts"`,
    'project_knowledge = "{project-root}/docs"',
    '',
    '[modules.bmb]',
    'bmad_builder_output_folder = "{project-root}/skills"',
    'bmad_builder_reports = "{project-root}/skills/reports"',
    '',
    '[modules.gds]',
    'planning_artifacts = "{project-root}/skills/planning-artifacts"',
    'implementation_artifacts = "{project-root}/skills/implementation-artifacts"',
    'project_knowledge = "{project-root}/docs"',
    '',
    '[modules.wds]',
    'design_artifacts = "{project-root}/design-artifacts"',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(bmad, 'config.toml'), toml, 'utf-8');

  fs.writeFileSync(path.join(bmad, 'gds', 'config.yaml'),
    [
      '# GDS Module Configuration',
      '# Generated by BMAD installer',
      '',
      'game_dev_experience: intermediate',
      'planning_artifacts: "{project-root}/skills/planning-artifacts"',
      'implementation_artifacts: "{project-root}/skills/implementation-artifacts"',
      'project_knowledge: "{project-root}/docs"',
      `output_folder: ${outputFolder}`,
      '',
    ].join('\n'), 'utf-8');

  fs.writeFileSync(path.join(bmad, 'bmm', 'config.yaml'),
    [
      '# BMM Module Configuration',
      '',
      `planning_artifacts: "${outputFolder}/planning-artifacts"`,
      `implementation_artifacts: "${outputFolder}/implementation-artifacts"`,
      'project_knowledge: "{project-root}/docs"',
      `output_folder: ${outputFolder}`,
      '',
    ].join('\n'), 'utf-8');
}

console.log('\n output-folder normalization tests (bug 27.14)\n');

// ── correctArtifactPath unit behaviour ───────────────────────────────────────
test('correctArtifactPath: rewrites a {project-root}-prefixed contaminated path', () => {
  assert.strictEqual(
    correctArtifactPath('{project-root}/skills/planning-artifacts', '_bmad-output'),
    '{project-root}/_bmad-output/planning-artifacts'
  );
});
test('correctArtifactPath: rewrites a stripped (relative) contaminated path', () => {
  assert.strictEqual(
    correctArtifactPath('skills/implementation-artifacts', '_bmad-output'),
    '_bmad-output/implementation-artifacts'
  );
});
test('correctArtifactPath: no change when already canonical', () => {
  assert.strictEqual(correctArtifactPath('{project-root}/_bmad-output/planning-artifacts', '_bmad-output'), null);
  assert.strictEqual(correctArtifactPath('_bmad-output/planning-artifacts', '_bmad-output'), null);
});
test('correctArtifactPath: tracks a CUSTOM output folder', () => {
  assert.strictEqual(
    correctArtifactPath('{project-root}/skills/planning-artifacts', 'my-docs'),
    '{project-root}/my-docs/planning-artifacts'
  );
});

// ── full pass with default output folder ─────────────────────────────────────
test('normalizes gds artifact paths in config.toml to the core output folder', () => {
  const dir = mktemp();
  try {
    writeContaminatedProject(dir, '_bmad-output');
    const changed = normalizeModuleOutputFolders(dir);
    assert.ok(changed >= 2, `expected >= 2 paths rewritten, got ${changed}`);

    const toml = fs.readFileSync(path.join(dir, '_bmad', 'config.toml'), 'utf-8');
    assert.ok(toml.includes('planning_artifacts = "{project-root}/_bmad-output/planning-artifacts"'),
      'gds planning_artifacts must track _bmad-output');
    assert.ok(toml.includes('implementation_artifacts = "{project-root}/_bmad-output/implementation-artifacts"'),
      'gds implementation_artifacts must track _bmad-output');
    // bmb own output folder must NOT be touched.
    assert.ok(toml.includes('bmad_builder_output_folder = "{project-root}/skills"'),
      'bmb own output folder must remain "skills"');
    assert.ok(toml.includes('bmad_builder_reports = "{project-root}/skills/reports"'),
      'bmb reports must remain under skills (not an artifact key)');
    // wds design-artifacts must NOT be touched.
    assert.ok(toml.includes('design_artifacts = "{project-root}/design-artifacts"'),
      'wds design_artifacts must be left alone');
  } finally { cleanup(dir); }
});

test('normalizes gds config.yaml artifact paths too', () => {
  const dir = mktemp();
  try {
    writeContaminatedProject(dir, '_bmad-output');
    normalizeModuleOutputFolders(dir);
    const gdsYaml = fs.readFileSync(path.join(dir, '_bmad', 'gds', 'config.yaml'), 'utf-8');
    assert.ok(gdsYaml.includes('_bmad-output/planning-artifacts'), 'gds yaml planning path normalized');
    assert.ok(gdsYaml.includes('_bmad-output/implementation-artifacts'), 'gds yaml impl path normalized');
    assert.ok(!gdsYaml.includes('skills/planning-artifacts'), 'no stray skills/ artifact path remains');
    // Header banner preserved.
    assert.ok(gdsYaml.startsWith('# GDS Module Configuration'), 'generated header preserved');
  } finally { cleanup(dir); }
});

test('CUSTOM output folder: gds paths track the custom folder (story AC)', () => {
  const dir = mktemp();
  try {
    writeContaminatedProject(dir, 'my-artifacts');
    normalizeModuleOutputFolders(dir);
    const toml = fs.readFileSync(path.join(dir, '_bmad', 'config.toml'), 'utf-8');
    assert.ok(toml.includes('[modules.gds]'), 'sanity: gds section present');
    assert.ok(toml.includes('planning_artifacts = "{project-root}/my-artifacts/planning-artifacts"'),
      'gds planning_artifacts must track the custom output folder');
    assert.ok(toml.includes('implementation_artifacts = "{project-root}/my-artifacts/implementation-artifacts"'),
      'gds implementation_artifacts must track the custom output folder');
    const gdsYaml = fs.readFileSync(path.join(dir, '_bmad', 'gds', 'config.yaml'), 'utf-8');
    assert.ok(gdsYaml.includes('my-artifacts/planning-artifacts'), 'gds yaml tracks custom folder');
  } finally { cleanup(dir); }
});

test('idempotent: a second pass rewrites nothing', () => {
  const dir = mktemp();
  try {
    writeContaminatedProject(dir, '_bmad-output');
    normalizeModuleOutputFolders(dir);
    const second = normalizeModuleOutputFolders(dir);
    assert.strictEqual(second, 0, 'second pass must be a no-op');
  } finally { cleanup(dir); }
});

test('no-op when config.toml absent', () => {
  const dir = mktemp();
  try {
    assert.strictEqual(normalizeModuleOutputFolders(dir), 0);
  } finally { cleanup(dir); }
});

test('invalid projectRoot is a no-op', () => {
  assert.strictEqual(normalizeModuleOutputFolders(undefined), 0);
  assert.strictEqual(normalizeModuleOutputFolders(''), 0);
});

console.log(`\n  ${passed} passed, ${failed} failed\n`);
if (failed > 0) {
  errors.forEach(e => console.error(`  ✗ ${e.name}: ${e.error}`));
  process.exit(1);
}

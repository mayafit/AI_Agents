// bug-jira-no-user-identity-context — Jira user-identity drift guard.
//
// The reported defect: a user asked for "the most important issue to work on"
// and got project-wide results, then could not narrow it to themselves because
// nothing in the Jira integration knew who they were. The Jira routing block
// named only `{jira_project_key}` at `{jira_url}` and never the operator, and a
// search for assignee/currentUser/accountId across all 13 sprint-management
// skills returned zero hits.
//
// The fix inserts an identity clause into every Jira routing block, resolving
// the operator via JQL `assignee = currentUser()`. This test is the drift guard:
// it fails if a routing block loses the clause, or if a NEW skill ships a Jira
// routing block without one — which is exactly how the gap would come back.
//
// It also pins the two rejected alternatives (OS login name, stored config id)
// so a future contributor cannot quietly reintroduce them: the clause must keep
// telling the agent NOT to use them, and no Jira config key may appear.

'use strict';

const assert = require('assert');
const { test } = require('node:test');
const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.join(__dirname, '..');

// Source trees only. `lib/bmad-extension-plugin/` is a generated byte-copy of
// `lib/bmad-extension/` (scripts/build-plugin.js) and `.agents/skills/` is a
// self-install artifact, so asserting on them would report the same defect
// several times and would fail spuriously mid-install.
const SOURCE_TREES = Object.freeze([
  'skills',
  path.join('lib', 'bmad-extension', 'skills'),
  path.join('lib', 'bmad-extension', 'workflows'),
]);

// The marker that identifies a Jira routing block.
const JIRA_BLOCK_MARKER = 'is `jira`';

// What the clause must establish.
const REQUIRED_CLAUSE = 'assignee = currentUser()';

function walkMarkdown(dir, out) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walkMarkdown(p, out);
    else if (entry.name.endsWith('.md')) out.push(p);
  }
  return out;
}

function jiraRoutedFiles() {
  const files = [];
  for (const tree of SOURCE_TREES) {
    for (const file of walkMarkdown(path.join(PROJECT_ROOT, tree), [])) {
      const text = fs.readFileSync(file, 'utf8');
      if (text.includes(JIRA_BLOCK_MARKER)) {
        files.push({ rel: path.relative(PROJECT_ROOT, file), text });
      }
    }
  }
  return files;
}

test('every Jira routing block is discoverable (guard is not vacuous)', () => {
  const files = jiraRoutedFiles();
  // A refactor that renames the routing-block marker would otherwise make every
  // assertion below pass over an empty set.
  assert.ok(
    files.length >= 20,
    `expected at least 20 files with a Jira routing block, found ${files.length} — ` +
      'has the routing-block marker changed?'
  );
});

test('every Jira routing block resolves identity via currentUser()', () => {
  const missing = jiraRoutedFiles()
    .filter((f) => !f.text.includes(REQUIRED_CLAUSE))
    .map((f) => f.rel);

  assert.deepStrictEqual(
    missing,
    [],
    'these Jira routing blocks cannot scope a query to the operating user — ' +
      `each must state \`${REQUIRED_CLAUSE}\`:\n  ${missing.join('\n  ')}`
  );
});

test('the identity clause rejects the OS login name', () => {
  const offenders = jiraRoutedFiles()
    .filter((f) => !/do NOT derive[\s\S]{0,200}OS login name/i.test(f.text))
    .map((f) => f.rel);

  assert.deepStrictEqual(
    offenders,
    [],
    'the clause must keep rejecting the OS login name as an identity source — a local ' +
      'account name has no defined relation to an Atlassian accountId (nothing on ' +
      'Cloud; possibly a DIFFERENT person on Server/DC). Missing in:\n  ' +
      offenders.join('\n  ')
  );
});

test('the identity clause forbids silently widening to project scope', () => {
  const offenders = jiraRoutedFiles()
    .filter((f) => !/Do NOT silently widen/i.test(f.text))
    .map((f) => f.rel);

  assert.deepStrictEqual(
    offenders,
    [],
    'when currentUser() resolves empty (shared service-account token) the skill must ' +
      'fail loud, not fall back to whole-project scope — that fallback IS the reported ' +
      'symptom. Missing in:\n  ' + offenders.join('\n  ')
  );
});

test('no Jira user identity is stored in config', () => {
  // Identity comes from the authenticated tool, never from a persisted field.
  // `bin/cli.js` is the only writer of Jira config keys (collectJiraConfig).
  const cli = fs.readFileSync(path.join(PROJECT_ROOT, 'bin', 'cli.js'), 'utf8');
  const forbidden = [
    'jira_account_id',
    'jira_user',
    'jira_username',
    'jira_email',
    'jiraAccountId',
    'jiraUsername',
    'jiraEmail',
  ];
  const found = forbidden.filter((key) => cli.includes(key));

  assert.deepStrictEqual(
    found,
    [],
    'a stored Jira identity goes stale on account change and is wrong for any repo ' +
      'shared between operators; resolve it with currentUser() instead. Found: ' +
      found.join(', ')
  );
});

test('a user-scoped selection skill exists in both pipelines', () => {
  // Defect B: identity alone does not answer "what should I work on next?" —
  // prioritize-backlog reorders the whole backlog with no assignee dimension,
  // sprint-status-view renders the whole board, and bmad-dev-story needs the
  // issue key up front.
  for (const rel of [
    path.join('skills', 'my-next-issue', 'SKILL.md'),
    path.join('lib', 'bmad-extension', 'skills', 'my-next-issue', 'SKILL.md'),
  ]) {
    const p = path.join(PROJECT_ROOT, rel);
    assert.ok(fs.existsSync(p), `missing user-scoped selection skill: ${rel}`);
    const text = fs.readFileSync(p, 'utf8');
    assert.ok(
      text.includes(REQUIRED_CLAUSE),
      `${rel} must scope its query with \`${REQUIRED_CLAUSE}\``
    );
    assert.ok(
      /READ-ONLY SKILL/.test(text),
      `${rel} must declare itself read-only — it selects and reports, it does not ` +
        'transition, assign, or reorder anything'
    );
  }
});
